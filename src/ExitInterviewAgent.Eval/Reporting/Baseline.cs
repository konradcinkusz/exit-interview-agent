using System.Text.Json;
using System.Text.Json.Nodes;
using ExitInterviewAgent.Eval.Scenarios;
using ExitInterviewAgent.Eval.Stats;

namespace ExitInterviewAgent.Eval.Reporting;

public sealed record BaselineMetric(int K, int N);

/// <summary>
/// The recorded state a regression is measured against (evals/baseline.json), pinned to the spec version, the corpus digest, the harness version and
/// the profile. The harness refuses to compare across any of them: a baseline compared across a change is a measuring stick that changed length.
/// A baseline never softens a constraint, and regenerating it needs a justification that the PR description repeats.
/// </summary>
public sealed class Baseline
{
    public const string HarnessVersion = "1.0.0";

    public string SpecVersion { get; init; } = "";
    public string HarnessVer { get; init; } = "";
    public string CorpusDigest { get; init; } = "";
    public string Profile { get; init; } = "";
    public string Recorded { get; init; } = "";
    public string Justification { get; init; } = "";
    public Dictionary<string, double> Tolerances { get; init; } = [];
    public double TokensRelativeTolerance { get; init; } = 0.10;
    public double TokensMean { get; init; }
    public Dictionary<string, string> Scenarios { get; init; } = [];
    public Dictionary<string, BaselineMetric> Metrics { get; init; } = [];

    /// <summary>The tolerance (an absolute drop in rate) a gated metric may move before the gate fails. Deterministic profiles default to 0.</summary>
    public double ToleranceOf(string metric) => Tolerances.TryGetValue(metric, out var t) ? t : Tolerances.GetValueOrDefault("default", 0.0);

    public static Baseline Load(string? path = null)
    {
        path ??= RepoLayout.BaselinePath;
        if (!File.Exists(path)) throw new FileNotFoundException($"No baseline at '{path}'. A suite with no recorded state cannot tell a regression from a Tuesday: run `baseline --justification \"...\"`.");
        var root = JsonNode.Parse(File.ReadAllText(path))!.AsObject();
        return new Baseline
        {
            SpecVersion = root["specVersion"]!.GetValue<string>(),
            HarnessVer = root["harnessVersion"]!.GetValue<string>(),
            CorpusDigest = root["corpusDigest"]!.GetValue<string>(),
            Profile = root["profile"]!.GetValue<string>(),
            Recorded = root["recorded"]!.GetValue<string>(),
            Justification = root["justification"]!.GetValue<string>(),
            Tolerances = root["tolerances"]!.AsObject().ToDictionary(p => p.Key, p => p.Value!.GetValue<double>()),
            TokensRelativeTolerance = root["tokens"]!["relativeTolerance"]!.GetValue<double>(),
            TokensMean = root["tokens"]!["mean"]!.GetValue<double>(),
            Scenarios = root["scenarios"]!.AsObject().ToDictionary(p => p.Key, p => p.Value!.GetValue<string>()),
            Metrics = root["metrics"]!.AsObject().ToDictionary(p => p.Key, p => new BaselineMetric(p.Value!["k"]!.GetValue<int>(), p.Value!["n"]!.GetValue<int>())),
        };
    }

    public static string Serialize(string specVersion, string digest, string profile, string justification, IReadOnlyDictionary<string, string> scenarios,
        IReadOnlyDictionary<string, Count> metrics, double tokensMean, IReadOnlyDictionary<string, double>? tolerances, double tokensTolerance, string recorded)
    {
        var tol = new JsonObject();
        foreach (var (k, v) in (tolerances ?? new Dictionary<string, double> { ["default"] = 0.0 }).OrderBy(x => x.Key == "default" ? "" : x.Key, StringComparer.Ordinal)) tol[k] = v;
        var met = new JsonObject();
        foreach (var (k, v) in metrics.OrderBy(x => x.Key, StringComparer.Ordinal)) met[k] = new JsonObject { ["k"] = v.K, ["n"] = v.N };
        var scn = new JsonObject();
        foreach (var (k, v) in scenarios.OrderBy(x => x.Key, StringComparer.Ordinal)) scn[k] = v;
        var root = new JsonObject
        {
            ["specVersion"] = specVersion,
            ["harnessVersion"] = HarnessVersion,
            ["corpusDigest"] = digest,
            ["profile"] = profile,
            ["recorded"] = recorded,
            ["justification"] = justification,
            ["comment"] = "Generated by `eval baseline --justification \"...\"`; do not edit by hand except `tolerances`. A gated behaviour metric may not fall (or, for lower-is-better metrics, rise) by more than its tolerance, an absolute change in rate; 'default' applies to any metric not listed. Constraints are never read from this file.",
            ["tolerances"] = tol,
            ["tokens"] = new JsonObject { ["mean"] = Math.Round(tokensMean, 3), ["relativeTolerance"] = tokensTolerance },
            ["scenarios"] = scn,
            ["metrics"] = met,
        };
        return root.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";
    }
}
